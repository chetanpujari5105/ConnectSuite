/**
 * Does the concealed-clipboard marker survive into Electron, on a pasteboard that also holds text?
 *
 * ### Why this had to be re-run
 *
 * Slice 12's first attempt proved the marker is **readable** and could not prove the case that
 * matters. `clipboard.write({ [TYPE]: … })` silently drops a custom type and `writeBuffer` replaces
 * the whole pasteboard, so Electron could build "marker, no text" and "text, no marker" and never
 * "text **and** marker" — which is the only shape a password manager produces. The positive control
 * failed to be positive, and the check shipped as defence in depth over an unmeasured input.
 *
 * `scripts/support/write-marked-clip.swift` builds it through `NSPasteboard`, which is the same API
 * 1Password calls. The stimulus is now real; only the reading is Electron's.
 *
 * ### What each row is for
 *
 * Every marked row is paired with an unmarked control carrying the same text, because "the check
 * returned true" means nothing unless the same check returns false one line later. And the text is
 * read back on every row: a marker check that worked by making the text unreadable would be no use
 * — the product has to know it is holding something it must not send, not merely fail to hold it.
 *
 * Run: cd desktop && npx electron ../scripts/clip-conceal-probe.mjs
 */
import { app, clipboard } from 'electron';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';

const WRITER = join(dirname(fileURLToPath(import.meta.url)), 'support', 'write-marked-clip.swift');
const CONCEALED = 'org.nspasteboard.ConcealedType';
const TRANSIENT = 'org.nspasteboard.TransientType';
const AUTOGEN = 'org.nspasteboard.AutoGeneratedType';

const write = (text, ...markers) => execFileSync('swift', [WRITER, text, ...markers], { encoding: 'utf8' });
/**
 * `has`, not `read`, and the difference is the whole finding.
 *
 * The convention writes the marker as a **present type carrying empty data** — that is what
 * `NSPasteboard.setData(Data(), forType:)` puts there and what the documented implementations do.
 * So `read(type) !== ''` is false for every real password-manager clip ever written, and the first
 * version of this check used exactly that. Its "positive control" passed only because the control
 * wrote `'1'` as the marker's value, which nothing in the wild does: the control and the real input
 * differed in the one attribute the check was reading.
 */
const marked = (type) => {
  try {
    return clipboard.has(type);
  } catch (error) {
    return `THREW: ${error.message}`;
  }
};
const readMarker = (type) => {
  try {
    return `has=${marked(type)} read=${JSON.stringify(clipboard.read(type))}`;
  } catch (error) {
    return `THREW: ${error.message}`;
  }
};

app.whenReady().then(() => {
  const theirs = clipboard.readText();
  const rows = [];

  const probe = (label, text, ...markers) => {
    write(text, ...markers);
    rows.push({
      label,
      text: clipboard.readText(),
      concealed: readMarker(CONCEALED),
      transient: readMarker(TRANSIENT),
      autogen: readMarker(AUTOGEN),
      formats: clipboard.availableFormats(),
    });
  };

  probe('text + ConcealedType — the 1Password shape', 'hunter2-not-a-real-password', CONCEALED);
  probe('CONTROL: the same text, no marker', 'hunter2-not-a-real-password');
  probe('text + TransientType', 'a transient clip', TRANSIENT);
  probe('text + AutoGeneratedType', 'an auto-generated clip', AUTOGEN);
  probe('text + all three markers', 'belt and braces', CONCEALED, TRANSIENT, AUTOGEN);
  probe('CONTROL: ordinary text again, to prove the marker clears', 'ordinary again');

  for (const r of rows) {
    console.log(`\n${r.label}`);
    console.log(`  readText()            ${JSON.stringify(r.text)}`);
    console.log(`  read(Concealed)       ${JSON.stringify(r.concealed)}`);
    console.log(`  read(Transient)       ${JSON.stringify(r.transient)}`);
    console.log(`  read(AutoGenerated)   ${JSON.stringify(r.autogen)}`);
    console.log(`  availableFormats()    ${JSON.stringify(r.formats)}`);
  }

  clipboard.writeText(theirs);
  console.log(`\nClipboard restored: ${clipboard.readText() === theirs ? 'yes' : 'NO — RESTORE FAILED'}\n`);
  app.exit(0);
});
