import assert from 'node:assert/strict';
import { createHash, randomBytes } from 'node:crypto';
import { existsSync, mkdtempSync, readdirSync, readFileSync } from 'node:fs';
import { createConnection, createServer, type Server } from 'node:net';
import type { TLSSocket } from 'node:tls';
import { tmpdir } from 'node:os';
import { basename, join } from 'node:path';
import test from 'node:test';

import { BulkClient } from './bulk';
import { failedPathFor } from '../shared/transferFiles';

/**
 * S9 (2026-10-07): the **pre-hash** pull — the path every release-build Files and Photos pull takes, since
 * `fs.blocks` is gated off — end to end through the product's `BulkClient.pull` over a real local socket,
 * against a fake phone serving generated bytes. Only TLS is replaced (plain TCP, as in `bulkBlockPull`).
 *
 * The block path has 40+ tests (`filesResume`, `bulkBlockPull`); this path had none of its own, and it is the
 * one that decides whether "checksum matched" may be said at all. Synthetic bytes in temp folders only.
 */

const T = { timeout: 20_000 };
const sha = (b: Uint8Array): string => createHash('sha256').update(b).digest('hex');

function phone(bytes: Buffer, chunk = 3000): Promise<{ port: number; close(): Promise<void> }> {
  return new Promise((ready) => {
    const server: Server = createServer((socket) => {
      socket.on('error', () => undefined);
      socket.on('data', () => undefined);
      for (let at = 0; at < bytes.length; at += chunk) {
        const piece = bytes.subarray(at, Math.min(bytes.length, at + chunk));
        const len = Buffer.alloc(4);
        len.writeUInt32BE(piece.length);
        socket.write(Buffer.concat([len, piece]));
      }
      socket.end();
    });
    server.listen(0, '127.0.0.1', () => {
      const a = server.address();
      ready({ port: typeof a === 'object' && a ? a.port : 0, close: () => new Promise((d) => server.close(() => d())) });
    });
  });
}

async function pull(served: Buffer, expectedBytes: number, expectedSha256: string | null, folder: string, name = 'f.bin') {
  const p = await phone(served);
  try {
    return await new BulkClient({} as never).pull({
      host: '127.0.0.1', token: 'tok', transferId: 't-pre', destination: join(folder, name),
      expectedBytes, expectedSha256,
      connect: () => ({ socket: createConnection({ host: '127.0.0.1', port: p.port }) as unknown as TLSSocket, readyEvent: 'connect' }),
    });
  } finally {
    await p.close();
  }
}

const folder = () => mkdtempSync(join(tmpdir(), 'sidekick-prehash-'));

test('an agreed digest that matches: saved, verified, verifiedBy prehash, no partial', T, async () => {
  const bytes = randomBytes(50_000);
  const dir = folder();
  const r = await pull(bytes, bytes.length, sha(bytes), dir);
  assert.equal(r.ok, true, r.reason);
  assert.equal(r.verified, true);
  assert.equal(r.verifiedBy, 'prehash');
  assert.equal(sha(readFileSync(join(dir, 'f.bin'))), sha(bytes));
  assert.deepEqual(readdirSync(dir), ['f.bin']);
});

test('a digest that does not match: nothing saved, the partial deleted, a .failed marker left, never verified', T, async () => {
  const bytes = randomBytes(50_000);
  const dir = folder();
  const r = await pull(bytes, bytes.length, 'ab'.repeat(32), dir);
  assert.equal(r.ok, false);
  assert.equal(r.verified, false);
  assert.match(r.reason ?? '', /different checksum/);
  assert.equal(existsSync(join(dir, 'f.bin')), false);
  const marker = basename(failedPathFor(join(dir, 'f.bin')));
  assert.deepEqual(readdirSync(dir), [marker], 'only the marker: no partial, no file');
});

/** Above the phone's 64 MiB pre-hash ceiling the ack carries no digest. Saved — and said to be unchecked. */
test('no digest agreed: saved on length, verified false, and no verifiedBy invented', T, async () => {
  const bytes = randomBytes(50_000);
  const dir = folder();
  const r = await pull(bytes, bytes.length, null, dir);
  assert.equal(r.ok, true, r.reason);
  assert.equal(r.verified, false);
  assert.equal(r.verifiedBy, undefined);
});

test('an empty file with the empty digest: saved as a 0-byte file and verified', T, async () => {
  const empty = Buffer.alloc(0);
  const dir = folder();
  const r = await pull(empty, 0, sha(empty), dir);
  assert.equal(r.ok, true, r.reason);
  assert.equal(r.verified, true);
  assert.equal(readFileSync(join(dir, 'f.bin')).length, 0);
});

test('an empty file against a non-empty digest is refused like any mismatch', T, async () => {
  const dir = folder();
  const r = await pull(Buffer.alloc(0), 0, sha(Buffer.from('not empty')), dir);
  assert.equal(r.ok, false);
  assert.equal(existsSync(join(dir, 'f.bin')), false);
});

/** A phone that hangs up early: the bytes on disk are a prefix and must not be published as the file. */
test('a short stream is not saved and not called verified', T, async () => {
  const bytes = randomBytes(50_000);
  const dir = folder();
  const r = await pull(bytes.subarray(0, 20_000), bytes.length, sha(bytes), dir);
  assert.equal(r.ok, false);
  assert.equal(r.verified, false);
  assert.equal(existsSync(join(dir, 'f.bin')), false);
});

test('a short stream with no digest is still not saved — length is the only check, and it failed', T, async () => {
  const bytes = randomBytes(50_000);
  const dir = folder();
  const r = await pull(bytes.subarray(0, 20_000), bytes.length, null, dir);
  assert.equal(r.ok, false);
  assert.equal(existsSync(join(dir, 'f.bin')), false);
});

test('a phone that sends more than it agreed is refused, not truncated into a "match"', T, async () => {
  const bytes = randomBytes(50_000);
  const dir = folder();
  const extra = Buffer.concat([bytes, randomBytes(1_000)]);
  const r = await pull(extra, bytes.length, sha(bytes), dir);
  assert.equal(r.ok, false);
  assert.equal(r.verified, false);
  assert.equal(existsSync(join(dir, 'f.bin')), false);
});

/**
 * Above 64 MiB there is no digest, so the agreed length is the **only** check. The test above carries a
 * digest, which also catches an over-long stream — mutation MT2 (the length check deleted) stayed green
 * against it. This is the case where the length check is alone.
 */
test('a phone that sends more than it agreed, with no digest, is refused on length alone', T, async () => {
  const bytes = randomBytes(50_000);
  const dir = folder();
  const r = await pull(Buffer.concat([bytes, randomBytes(1_000)]), bytes.length, null, dir);
  assert.equal(r.ok, false);
  assert.match(r.reason ?? '', /sent \d+ bytes where 50000 were agreed/);
  assert.equal(existsSync(join(dir, 'f.bin')), false);
});
