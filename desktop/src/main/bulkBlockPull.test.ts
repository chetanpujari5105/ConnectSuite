import assert from 'node:assert/strict';
import { createHash, randomBytes } from 'node:crypto';
import { existsSync, mkdtempSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createConnection, createServer, type Server } from 'node:net';
import type { TLSSocket } from 'node:tls';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';

import { BulkClient } from './bulk';
import { BlockPullVerifier, blockCountFor, rootOf } from '../shared/fsBlocks';
import { failedPathFor, pullPartPathFor } from '../shared/transferFiles';

/**
 * `fs.blocks` on the Mac, end to end: the product's `BulkClient.pull` over a **real local socket**
 * against a fake phone that serves generated bytes, while this test plays the control channel —
 * feeding `fs.transfer.blocks` and `fs.transfer.done` to the verifier exactly as `FilesClient` does.
 * Only TLS is replaced, by plain TCP, as in `bulkPush.test.ts`. Nothing here reads a personal file.
 */

const T = { timeout: 20_000 };
const BS = 4096;
const sha = (b: Uint8Array): string => createHash('sha256').update(b).digest('hex');

interface Phone { port: number; close(): Promise<void> }

/** Serves [bytes] as bulk frames of [chunk] after the Mac's token and header, then closes. */
function phone(bytes: Buffer, chunk = 3000): Promise<Phone> {
  return new Promise((ready) => {
    const server: Server = createServer((socket) => {
      socket.on('error', () => undefined);
      socket.on('data', () => undefined);
      for (let at = 0; at < bytes.length; at += chunk) {
        const piece = bytes.subarray(at, Math.min(bytes.length, at + chunk));
        const len = Buffer.alloc(4);
        len.writeUInt32BE(piece.length);
        socket.write(Buffer.concat([len, piece]));
      }
      socket.end();
    });
    server.listen(0, '127.0.0.1', () => {
      const a = server.address();
      ready({ port: typeof a === 'object' && a ? a.port : 0, close: () => new Promise((d) => server.close(() => d())) });
    });
  });
}

function source(n = 10 * BS + 123): { bytes: Buffer; digests: string[]; done: Record<string, unknown>; count: number } {
  const bytes = randomBytes(n);
  const count = blockCountFor(n, BS);
  const digests = Array.from({ length: count }, (_, i) => sha(bytes.subarray(i * BS, Math.min(n, (i + 1) * BS))));
  return { bytes, digests, count, done: { ok: true, bytes: n, sha256: sha(bytes), blockSize: BS, blockCount: count, manifestRoot: rootOf(digests) } };
}

async function pull(served: Buffer, size: number, verifier: BlockPullVerifier, folder: string, name = 'clip.bin', waitMs = 2000) {
  const p = await phone(served);
  try {
    return await new BulkClient({} as never).pull({
      host: '127.0.0.1',
      token: 'tok',
      transferId: 't-test',
      destination: join(folder, name),
      expectedBytes: size,
      expectedSha256: null,
      blocks: verifier,
      blockDoneWaitMs: waitMs,
      connect: () => ({ socket: createConnection({ host: '127.0.0.1', port: p.port }) as unknown as TLSSocket, readyEvent: 'connect' }),
    });
  } finally {
    await p.close();
  }
}

const folder = () => mkdtempSync(join(tmpdir(), 'sidekick-blocks-'));

test('a faithful block pull is saved only after done, verified block by block, with no partial left', T, async () => {
  const s = source();
  const dir = folder();
  const v = new BlockPullVerifier(s.bytes.length, BS, s.count);
  v.onBlocks({ first: 0, sha256: s.digests });
  setTimeout(() => v.onDone(s.done), 50);
  const r = await pull(s.bytes, s.bytes.length, v, dir);
  assert.equal(r.ok, true, r.reason);
  assert.equal(r.verified, true);
  assert.equal(r.verifiedBy, 'blocks');
  assert.equal(r.verifiedBlocks, s.count);
  assert.equal(sha(readFileSync(join(dir, 'clip.bin'))), sha(s.bytes));
  assert.deepEqual(readdirSync(dir), ['clip.bin'], 'no partial, no sidecar');
});

test('one flipped byte: nothing is saved, the partial is deleted, a .failed sidecar says why', T, async () => {
  const s = source();
  const dir = folder();
  const bad = Buffer.from(s.bytes);
  bad[5 * BS + 9] ^= 0xff;
  const v = new BlockPullVerifier(s.bytes.length, BS, s.count);
  v.onBlocks({ first: 0, sha256: s.digests });
  v.onDone(s.done);
  const r = await pull(bad, s.bytes.length, v, dir);
  assert.equal(r.ok, false);
  assert.equal(r.verified, false);
  assert.equal(r.verifiedBlocks, 5, 'the blocks before the damage were verified');
  assert.ok(r.bytes < s.bytes.length, `it stopped at the damaged block, not at the end (${r.bytes} of ${s.bytes.length})`);
  assert.match(r.reason ?? '', /damaged/);
  assert.equal(existsSync(join(dir, 'clip.bin')), false, 'never published');
  assert.equal(existsSync(pullPartPathFor(join(dir, 'clip.bin'))), false, 'the corrupt partial is deleted');
  assert.ok(existsSync(failedPathFor(join(dir, 'clip.bin'))), `a sidecar: ${readdirSync(dir).join(', ')}`);
});

test('SOURCE_CHANGED from the phone: not saved, partial deleted, reported as a changed source', T, async () => {
  const s = source();
  const dir = folder();
  const v = new BlockPullVerifier(s.bytes.length, BS, s.count);
  v.onBlocks({ first: 0, sha256: s.digests });
  setTimeout(() => v.onDone({ ok: false, code: 'SOURCE_CHANGED', why: 'source-changed', message: 'clip.bin changed on the phone while it was being sent, so it was not saved.' }), 30);
  const r = await pull(s.bytes, s.bytes.length, v, dir);
  assert.equal(r.ok, false);
  assert.equal(r.sourceChanged, true);
  assert.match(r.reason ?? '', /changed on the phone/);
  assert.equal(existsSync(join(dir, 'clip.bin')), false);
  assert.equal(existsSync(pullPartPathFor(join(dir, 'clip.bin'))), false);
});

test('no done from the phone: nothing is published and the partial is kept for a resume', T, async () => {
  const s = source();
  const dir = folder();
  const v = new BlockPullVerifier(s.bytes.length, BS, s.count);
  v.onBlocks({ first: 0, sha256: s.digests });
  const r = await pull(s.bytes, s.bytes.length, v, dir, 'clip.bin', 100);
  assert.equal(r.ok, false);
  assert.equal(r.noVerdict, true);
  assert.equal(existsSync(join(dir, 'clip.bin')), false, 'never published without a verdict');
  assert.equal(readFileSync(pullPartPathFor(join(dir, 'clip.bin'))).length, s.bytes.length, 'the partial is kept whole');
});

test('exclusive save: a file already at the name is never replaced; the pull takes the next name', T, async () => {
  const s = source();
  const dir = folder();
  writeFileSync(join(dir, 'clip.bin'), 'the person’s own file');
  const v = new BlockPullVerifier(s.bytes.length, BS, s.count);
  v.onBlocks({ first: 0, sha256: s.digests });
  v.onDone(s.done);
  const r = await pull(s.bytes, s.bytes.length, v, dir);
  assert.equal(r.ok, true, r.reason);
  assert.equal(readFileSync(join(dir, 'clip.bin'), 'utf8'), 'the person’s own file');
  assert.equal(r.path, join(dir, 'clip (2).bin'));
  assert.equal(sha(readFileSync(join(dir, 'clip (2).bin'))), sha(s.bytes));
});

test('control: without a verifier the pull keeps the old path — saved on length, not block-verified', T, async () => {
  const s = source();
  const dir = folder();
  const p = await phone(s.bytes);
  try {
    const r = await new BulkClient({} as never).pull({
      host: '127.0.0.1', token: 'tok', transferId: 't-old', destination: join(dir, 'old.bin'),
      expectedBytes: s.bytes.length, expectedSha256: null,
      connect: () => ({ socket: createConnection({ host: '127.0.0.1', port: p.port }) as unknown as TLSSocket, readyEvent: 'connect' }),
    });
    assert.equal(r.ok, true);
    assert.equal(r.verified, false, 'an older phone’s large pull is still reported unverified');
    assert.equal(r.verifiedBy, undefined);
  } finally {
    await p.close();
  }
});
