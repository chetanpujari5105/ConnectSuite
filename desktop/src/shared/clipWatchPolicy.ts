/**
 * What a clipboard watcher may send, and how often it may look. The Electron-free half.
 *
 * `NSPasteboard` has **no change notification** — no callback, no KVO, nothing — and Electron
 * exposes no `changeCount` either, so a watcher on macOS polls and reads. That makes two questions
 * design questions rather than footnotes, and both are answered from measurements in
 * `docs/testing.md` → Slice 13.
 *
 * ### What must never be sent
 *
 * A watcher sees every copy somebody makes all day, and some of those are passwords. macOS has a
 * convention for saying so — `org.nspasteboard.ConcealedType` and its two siblings — and the
 * measurement that matters is not whether the convention exists but whether **Electron can see a
 * marker a real app wrote**. It can, through `clipboard.has`, and only through `has`:
 *
 * | | text present | marker present | `has(marker)` | `read(marker)` |
 * |---|---|---|---|---|
 * | 1Password shape, written via `NSPasteboard` | yes | yes | **`true`** | `""` |
 * | same text, no marker — the control | yes | no | `false` | `""` |
 *
 * **`read` is `""` in both rows**, because the convention writes the marker as a present type
 * carrying *empty data*. The first version of this check used `read(type) !== ''` and could
 * therefore never have fired on a real password manager; it passed its own control only because the
 * control wrote a value — `'1'` — that nothing in the wild writes. The control and the real input
 * differed in the exact attribute being read.
 *
 * All three markers are honoured, not just the concealed one. A transient or auto-generated clip is
 * one an app has explicitly asked clipboard managers not to record, and sending it to another
 * device is the same act under a different name.
 *
 * ### The residual risk, stated rather than implied
 *
 * An app that copies a password and sets **no** marker is indistinguishable from an app that copies
 * a URL. Nothing here can fix that, so the rest of the design carries it: the phone holds arriving
 * entries rather than applying them by default, both histories are memory-only and cleared on
 * disconnect, no clipboard text is logged at any level, and the watcher can be turned off.
 */

/** The macOS marker types, in the order they are checked. All three are honoured. */
export const MARKER_TYPES = Object.freeze([
  'org.nspasteboard.ConcealedType',
  'org.nspasteboard.TransientType',
  'org.nspasteboard.AutoGeneratedType',
] as const);

export type MarkerType = (typeof MARKER_TYPES)[number];

/** Why a poll produced nothing to send. `null` means send it. */
export type SkipReason = 'empty' | 'concealed' | 'transient' | 'auto-generated' | 'too large';

const MARKER_REASON: Record<MarkerType, SkipReason> = {
  'org.nspasteboard.ConcealedType': 'concealed',
  'org.nspasteboard.TransientType': 'transient',
  'org.nspasteboard.AutoGeneratedType': 'auto-generated',
};

/**
 * Whether this clipboard reading may leave the machine.
 *
 * `markers` is the set the caller found with `clipboard.has` — passed in rather than read here, so
 * the decision is testable without a pasteboard and so there is exactly one place that knows the
 * marker names.
 *
 * **Order matters and is not alphabetical.** A concealed clip that is also over the size cap is
 * reported as *concealed*: the size is incidental and the concealment is the fact worth counting,
 * and a log line that said "too large" about a password would be the more alarming of two true
 * statements told wrongly.
 */
export function skipReason(text: string, markers: ReadonlySet<string>, tooLarge: boolean): SkipReason | null {
  for (const type of MARKER_TYPES) {
    if (markers.has(type)) return MARKER_REASON[type];
  }
  if (text.length === 0) return 'empty';
  if (tooLarge) return 'too large';
  return null;
}

/** The floor: fast enough that a copy-then-paste feels immediate, slow enough to cost nothing. */
export const MIN_INTERVAL_MS = 500;

/** The ceiling: past here the watcher is no longer watching, it is checking occasionally. */
export const MAX_INTERVAL_MS = 5_000;

/** One percent of one core. The watcher is a background convenience and gets a background budget. */
export const DUTY_CYCLE = 0.01;

/**
 * How long to wait before the next poll, given how long the last read took.
 *
 * **Derived from the measured read rather than from the clipboard's size**, which is the same rule
 * as everywhere else in this repo: measure the effect, not the stimulus. A size table would encode
 * one machine's performance as a constant, and this adapts to a slow machine, a busy machine and a
 * faster one later, all with the same expression.
 *
 * The numbers it is calibrated against (`docs/testing.md` → Slice 13, median of 200 reads each):
 *
 * | clipboard | one `readText()` | at the floor |
 * |---|---|---|
 * | empty | 0.0010 ms | nothing |
 * | 64 KB — our own send cap | 0.1008 ms | 0.02 % of a core |
 * | 1 MB | 2.0355 ms | 0.4 % |
 * | 20 MB | 37.2974 ms | 7.5 % — which is why this function exists |
 *
 * A 20 MB clipboard backs off to 3.7 s and costs 1 % instead of 7.5 %. Nothing is missed by it: a
 * clipboard that large is over the 64 KB cap and would be refused anyway, so the slow poll is
 * waiting for it to become something sendable again.
 */
export function nextIntervalMs(lastReadMs: number): number {
  const forBudget = lastReadMs / DUTY_CYCLE;
  return Math.min(MAX_INTERVAL_MS, Math.max(MIN_INTERVAL_MS, Math.round(forBudget)));
}
