package com.chetan.connectsuite.sync.v2

import com.chetan.connectsuite.sync.v2.ShareOffer.Effect
import com.chetan.connectsuite.sync.v2.ShareOffer.PullEnd
import com.chetan.connectsuite.sync.v2.ShareOffer.Reply
import com.chetan.connectsuite.sync.v2.ShareOffer.Side
import com.chetan.connectsuite.sync.v2.ShareOffer.State
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.ByteArrayInputStream
import java.io.File
import java.io.RandomAccessFile
import java.nio.file.Files
import kotlin.random.Random

/**
 * The held-copy check against **real staged copies** made by the production [ShareStaging.copy] from
 * generated bytes (no media, no `content:` source): each offer is judged by its own `<offerId>.bin`, a
 * copy genuinely removed while waiting ends only its own offer as `staging-lost`, cleanup removes only
 * that offer's files, and an intact copy goes through the same checks, the Accept and a whole version-2
 * transfer to Saved. `ShareFeature`'s loop calls [ShareHeldCopies.check] — the function exercised here.
 *
 * Not reached from a JVM test: the loop's 30 s timer and `ShareFeature.apply` itself (it needs a live
 * `LinkServer`). Where this test applies a DeleteStaged effect it does what `apply` does —
 * [ShareStaging.discard] on the offer's id — and says so at the call.
 */
class ShareHeldCopiesTest {

    private val t0 = 1_000_000L
    private val key = "token-A"
    private val tx = "ts-AAAAAAAAAAAAAAAAAAAAAA"
    private val lost = State.Cancelled(Side.PHONE, "staging-lost")

    private fun cache(): File = Files.createTempDirectory("held").toFile()
    private fun stagingIn(cache: File) = File(cache, ShareStaging.DIR_NAME).apply { mkdirs() }

    /** Stage [n] generated bytes through the production copy, and make the offer for it. */
    private fun stage(dir: File, n: Int, seed: Int): ShareOffer.Offer {
        val id = ShareStaging.newAttemptId()
        val out = ShareStaging.copy(ByteArrayInputStream(Random(seed).nextBytes(n)), dir, id, Long.MAX_VALUE, { Long.MAX_VALUE }, { false }, t0)
        val staged = out as ShareStaging.Outcome.Staged
        return ShareOffer.Offer(id, key, staged.bytes, staged.sha256, t0, t0 + ShareOffer.TTL_MS, name = "synthetic-$seed.bin")
    }

    private fun names(dir: File) = (dir.list() ?: emptyArray()).sorted()

    /** What `ShareFeature.apply` does for [Effect.DeleteStaged]: discard that offer's own files. */
    private fun applyDelete(dir: File, r: ShareOffer.Result) {
        if (Effect.DeleteStaged in r.effects) ShareStaging.discard(dir, r.offer!!.offerId)
    }

    @Test fun `a copy genuinely removed while waiting ends only its own offer, and cleanup removes only its files`() {
        val dir = stagingIn(cache())
        val a = stage(dir, 4096, seed = 1)
        val b = stage(dir, 8192, seed = 2)
        assertEquals("control: both copies staged, with their markers",
            listOf("${a.offerId}.bin", "${a.offerId}.json", "${b.offerId}.bin", "${b.offerId}.json").sorted(), names(dir))
        assertTrue("control: both intact before the removal", ShareHeldCopies.intact(dir, a) && ShareHeldCopies.intact(dir, b))

        assertTrue(File(dir, "${a.offerId}.bin").delete()) // what the platform's cache clearing does

        val (ra, rb) = ShareHeldCopies.tick(listOf(a, b), dir)
        assertEquals(lost, ra.offer!!.state)
        assertEquals(listOf(Effect.SendCancel("staging-lost"), Effect.DeleteStaged), ra.effects)
        assertEquals("the other offer is untouched", b, rb.offer)
        assertTrue(rb.effects.isEmpty())

        applyDelete(dir, ra)
        applyDelete(dir, rb)
        assertEquals("only the lost offer's leftovers are gone", listOf("${b.offerId}.bin", "${b.offerId}.json").sorted(), names(dir))
        assertTrue(ShareHeldCopies.intact(dir, b))
        // And once ended, it can never be pulled or saved.
        assertEquals("NOT_FOUND", (ShareOffer.beginPull(ra.offer, key, a.offerId, "0", tx, t0 + 5, 262144).reply as Reply.Error).code)
        assertFalse(ShareOffer.reportsSaved(ShareOffer.saved(ra.offer, key, a.offerId, true, a.bytes, true, "x.bin", null, t0 + 6).offer!!.state))
    }

    @Test fun `positive control - an intact copy passes the same checks, the Accept, and a whole version-2 transfer to Saved`() {
        val dir = stagingIn(cache())
        val a = stage(dir, 4096, seed = 3)
        val b = stage(dir, 4096, seed = 4)
        // Two passes of the timer: nothing changes, nothing is sent.
        repeat(2) { ShareHeldCopies.tick(listOf(a, b), dir).forEach { r -> assertTrue(r.effects.isEmpty()) } }
        val acc = ShareOffer.respond(a, key, a.offerId, "accept", null, t0 + 1, negotiatedVersion = 2, stagedIntact = ShareHeldCopies.intact(dir, a))
        assertEquals(Reply.Ack(mapOf("offerId" to a.offerId, "state" to "accepted")), acc.reply)
        assertTrue(ShareHeldCopies.check(dir, acc.offer!!).effects.isEmpty())
        val sending = ShareOffer.beginPull(acc.offer, key, a.offerId, "0", tx, t0 + 2, 262144).offer!!
        assertEquals(State.Sending, sending.state)
        assertEquals("a pull in flight is not judged by the timer", sending, ShareHeldCopies.check(dir, sending).offer)
        val awaiting = ShareOffer.pullEnded(sending, tx, PullEnd.SENT, t0 + 3).offer!!
        val saved = ShareOffer.saved(awaiting, key, a.offerId, true, a.bytes, true, "synthetic-3.bin", null, t0 + 4)
        assertTrue(ShareOffer.reportsSaved(saved.offer!!.state))
        applyDelete(dir, saved) // the saved offer's copy is cleaned up, and only it
        assertEquals(listOf("${b.offerId}.bin", "${b.offerId}.json").sorted(), names(dir))
    }

    @Test fun `each offer is judged by its own file - never another offer's, a leftover part, a marker, or a link`() {
        val dir = stagingIn(cache())
        val a = stage(dir, 4096, seed = 5)
        val b = stage(dir, 4096, seed = 6)
        File(dir, "${a.offerId}.bin").delete()
        File(dir, "${a.offerId}.part").writeBytes(ByteArray(4096)) // an unfinished copy with the right length is not a copy
        assertFalse("A is gone even though B's copy and A's marker and part are there", ShareHeldCopies.intact(dir, a))
        assertTrue(ShareHeldCopies.intact(dir, b))
        // A link where the copy should be is not a copy, even to a file of the right length.
        val elsewhere = File(cache(), "same-length.bin").apply { writeBytes(ByteArray(4096)) }
        Files.createSymbolicLink(File(dir, "${a.offerId}.bin").toPath(), elsewhere.toPath())
        assertFalse(ShareHeldCopies.intact(dir, a))
    }

    @Test fun `a copy of the wrong length is lost, and the length is checked exactly`() {
        val dir = stagingIn(cache())
        val a = stage(dir, 4096, seed = 7)
        RandomAccessFile(File(dir, "${a.offerId}.bin"), "rw").use { it.setLength(4095) }
        assertFalse(ShareHeldCopies.intact(dir, a))
        RandomAccessFile(File(dir, "${a.offerId}.bin"), "rw").use { it.setLength(4096) }
        assertTrue("control: the offered length is intact", ShareHeldCopies.intact(dir, a))
    }

    @Test fun `a missing staging folder means every copy is gone, and it is never created`() {
        val c = cache()
        val a = stage(stagingIn(c), 1024, seed = 8)
        val dir = File(c, ShareStaging.DIR_NAME)
        ShareStaging.discard(dir, a.offerId)
        assertTrue(dir.delete())
        assertEquals(lost, ShareHeldCopies.check(dir, a).offer!!.state)
        assertFalse("the check created the folder", dir.exists())
        assertFalse(ShareHeldCopies.intact(null, a))
    }
}
