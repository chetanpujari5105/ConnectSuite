/**
 * Stage B groundwork (PROPOSED, not wired, not registered): parsing a multi-select and staging it one
 * file at a time. Generated bytes (a few KiB each) in a JUnit temporary folder only; the "free space"
 * the copy reads is a number the test supplies, so nothing here uses real disk beyond the bytes written.
 */
class ShareSelectionTest {

    @get:Rule val tmp = TemporaryFolder()

    private val gib = 1024L * 1024 * 1024
    private val plenty = { 40 * gib }
    private fun dir(): File = tmp.newFolder()
    private fun names(d: File): Set<String> = d.list()!!.toSet()
    private fun sha(b: ByteArray) = MessageDigest.getInstance("SHA-256").digest(b).joinToString("") { "%02x".format(it) }
    private fun items(n: Int, mime: String = "image/jpeg") = List(n) { Item("content", mime) }
    private val send = ShareSelection.ACTION_SEND_MULTIPLE

    // ---- parsing -----------------------------------------------------------------------------------

    @Test fun `one to ten content items are taken, in the order given`() {
        for (n in 1..ShareSelection.MAX_FILES) assertEquals(Decision.Take(n), ShareSelection.decide(send, items(n), false))
        assertEquals(10, ShareSelection.MAX_FILES)
    }

    @Test fun `eleven are refused as a whole, never truncated to ten`() {
        assertEquals(Decision.Refuse(Refusal.TOO_MANY), ShareSelection.decide(send, items(11), false))
        assertEquals(Decision.Refuse(Refusal.TOO_MANY), ShareSelection.decide(send, items(500), false))
    }

    @Test fun `a single bad item refuses the selection and names its position`() {
        val mixed = items(4).toMutableList().also { it[2] = Item("file", "image/jpeg") }
        assertEquals(Decision.Refuse(Refusal.NOT_CONTENT, 3), ShareSelection.decide(send, mixed, false))
        val folder = items(4).toMutableList().also { it[1] = Item("content", "vnd.android.document/directory") }
        assertEquals(Decision.Refuse(Refusal.FOLDER, 2), ShareSelection.decide(send, folder, false))
        val noScheme = items(2).toMutableList().also { it[0] = Item(null, "image/png") }
        assertEquals(Decision.Refuse(Refusal.NOT_CONTENT, 1), ShareSelection.decide(send, noScheme, false))
    }

    @Test fun `the same URI twice refuses the selection, naming both positions - never sent twice, never dropped`() {
        fun keyed(vararg keys: String) = keys.map { Item("content", "image/png", it) }
        val u = "content://media/external/images/media/"
        assertEquals(Decision.Take(3), ShareSelection.decide(send, keyed(u + 1, u + 2, u + 3), false))
        assertEquals(Decision.Refuse(Refusal.DUPLICATE, 3, 1), ShareSelection.decide(send, keyed(u + 1, u + 2, u + 1), false))
        assertEquals(Decision.Refuse(Refusal.DUPLICATE, 2, 1), ShareSelection.decide(send, keyed(u + 7, u + 7), false))
        // The first repeat is the one named, in selection order.
        assertEquals(Decision.Refuse(Refusal.DUPLICATE, 4, 2), ShareSelection.decide(send, keyed(u + 1, u + 2, u + 3, u + 2, u + 1), false))
        // An exact comparison: a different id, or the same id on another authority, is a different item.
        assertEquals(Decision.Take(2), ShareSelection.decide(send, keyed(u + 1, u + 10), false))
        assertEquals(Decision.Take(2), ShareSelection.decide(send, keyed(u + 1, "content://com.sec.android.app.myfiles/1"), false))
        // Items with no key (as before this rule) are never judged repeats.
        assertEquals(Decision.Take(2), ShareSelection.decide(send, items(2), false))
    }

    @Test fun `a repeat is judged after the item checks and before another copy running`() {
        val u = "content://media/external/images/media/1"
        val bad = listOf(Item("content", "image/png", u), Item("file", "image/png", u))
        assertEquals("an unreadable item is named first", Decision.Refuse(Refusal.NOT_CONTENT, 2), ShareSelection.decide(send, bad, false))
        val twice = listOf(Item("content", "image/png", u), Item("content", "image/png", u))
        assertEquals(Decision.Refuse(Refusal.DUPLICATE, 2, 1), ShareSelection.decide(send, twice, true))
        assertEquals("one file is never a repeat", Decision.Take(1), ShareSelection.decide(send, twice.take(1), false))
    }

    @Test fun `not SEND_MULTIPLE, nothing in it, or another copy running are each refused`() {
        assertEquals(Decision.Refuse(Refusal.NOT_A_SEND_MULTIPLE), ShareSelection.decide(ShareIntake.ACTION_SEND, items(2), false))
        assertEquals(Decision.Refuse(Refusal.NOT_A_SEND_MULTIPLE), ShareSelection.decide(null, items(2), false))
        assertEquals(Decision.Refuse(Refusal.NO_FILES), ShareSelection.decide(send, emptyList(), false))
        assertEquals(Decision.Refuse(Refusal.ANOTHER_IN_PROGRESS), ShareSelection.decide(send, items(2), true))
    }

    @Test fun `the one-file intake still refuses SEND_MULTIPLE - nothing here changed it`() {
        assertEquals(ShareIntake.Decision.Refuse(ShareIntake.Refusal.NOT_A_SEND), ShareIntake.decide(send, "content", 2, "image/png", false))
    }

    @Test fun `group is display only, bounded, and its id has one shape`() {
        val id = ShareSelection.newGroupId()
        assertTrue(id, Regex("^g-[A-Za-z0-9_-]{22}$").matches(id))
        ShareSelection.Group(id, 10, 10)
        for ((index, count) in listOf(0 to 3, 4 to 3, 1 to 0, 1 to 11)) {
            try {
                ShareSelection.Group(id, index, count)
                throw AssertionError("index=$index count=$count was accepted")
            } catch (expected: IllegalArgumentException) {
            }
        }
    }

    // ---- whole-selection admission -----------------------------------------------------------------

    @Test fun `as shipped, with no approved cap, any selection of more than one file is refused before a byte is read`() {
        assertEquals(null, ShareAdmission.APPROVED_CAP)
        assertEquals(ShareBatch.Admission.Go, ShareBatch.admitSelection(listOf(100_718L), 0, ShareAdmission.APPROVED_CAP))
        for (n in 2..10) {
            assertEquals("n=$n", ShareBatch.Admission.CapNotApproved, ShareBatch.admitSelection(List(n) { 1000L }, 0, ShareAdmission.APPROVED_CAP))
        }
    }

    @Test fun `with a cap given (tests only), the known sizes plus what is held must fit it`() {
        assertEquals(ShareBatch.Admission.Go, ShareBatch.admitSelection(listOf(400L, 600L), 0, cap = 1000))
        assertEquals(ShareBatch.Admission.OverCap(1, 1000, 1000), ShareBatch.admitSelection(listOf(400L, 600L), 1, cap = 1000))
        assertEquals("unknown sizes are judged per file, later", ShareBatch.Admission.Go, ShareBatch.admitSelection(listOf(null, 600L), 0, cap = 1000))
    }

    // ---- staging, one at a time ---------------------------------------------------------------------

    private class Harness(val bytes: List<ByteArray>) {
        val offered = mutableListOf<Triple<Int, ShareSelection.Group, String>>()
        val offeredBytes = mutableMapOf<String, Long>()
        val opens = mutableListOf<Int>()
        var accept: (Int) -> Boolean = { true }
        fun offerer() = ShareBatch.Offerer { index, group, attemptId, size, _ ->
            val take = accept(index)
            if (take) {
                offered += Triple(index, group, attemptId)
                offeredBytes[attemptId] = size
            }
            take
        }
        fun open(i: Int): InputStream {
            opens += i
            return ByteArrayInputStream(bytes[i])
        }
        fun held() = offeredBytes.values.sum()
    }

    private fun batch(d: File, bytes: List<ByteArray>, expected: List<Long?> = bytes.map { it.size.toLong() }) =
        ShareBatch(d, ShareSelection.newGroupId(), expected)

    @Test fun `with a cap given (tests only), three files are copied in selection order, each offered on its own with its group`() {
        val d = dir()
        val h = Harness(List(3) { Random.nextBytes(2048 + it) })
        val b = batch(d, h.bytes)
        val out = b.run(3, cap = 1_000_000, held = h::held, free = plenty, open = h::open, offerer = h.offerer(), cancelled = { false }, nowMs = { 0 })
        assertEquals(listOf(0, 1, 2), h.opens)
        assertEquals(listOf(0, 1, 2), h.offered.map { it.first })
        assertEquals(listOf(1, 2, 3), h.offered.map { it.second.index })
        assertTrue(h.offered.all { it.second.count == 3 && it.second.id == h.offered[0].second.id })
        out.forEachIndexed { i, s ->
            s as FileState.Offered
            assertEquals(h.bytes[i].size.toLong(), s.bytes)
            assertEquals(sha(h.bytes[i]), s.sha256)
            assertTrue("the copy is on disk for its offer", File(d, "${s.offerId}.bin").readBytes().contentEquals(h.bytes[i]))
        }
        assertEquals("handed-over copies are never the batch's to delete", 0, b.discardUnoffered())
        assertEquals(6, names(d).size) // three .bin and three markers, all owned by their offers
    }

    @Test fun `as shipped (version 3, cap null) the batch driver itself refuses the second file, and keeps the first offer`() {
        val d = dir()
        val h = Harness(List(3) { Random.nextBytes(1024) })
        val out = batch(d, h.bytes).run(3, cap = ShareAdmission.APPROVED_CAP, held = h::held, free = plenty, open = h::open, offerer = h.offerer(), cancelled = { false }, nowMs = { 0 })
        assertTrue(out[0] is FileState.Offered)
        for (i in 1..2) assertEquals(FileState.Failed(Why.Admission(ShareAdmission.Copy.CapNotApproved(1024))), out[i])
        assertEquals("nothing of files 2 and 3 was read", listOf(0), h.opens)
    }

    @Test fun `below version 3 each file is judged by the one-file preflight alone - the batch never widens a version-2 session`() {
        val d = dir()
        val h = Harness(List(2) { Random.nextBytes(512) })
        val out = batch(d, h.bytes).run(2, cap = null, held = h::held, free = plenty, open = h::open, offerer = h.offerer(), cancelled = { false }, nowMs = { 0 })
        assertTrue(out.all { it is FileState.Offered })
    }

    @Test fun `one unreadable file fails alone, leaves no bytes, and the next is still copied and offered`() {
        val d = dir()
        val good = Random.nextBytes(4096)
        val h = Harness(listOf(good, good, good))
        val b = batch(d, h.bytes)
        val out = b.run(3, cap = 1_000_000, held = h::held, free = plenty, offerer = h.offerer(), cancelled = { false }, nowMs = { 0 },
            open = { i ->
                h.opens += i
                if (i == 1) object : InputStream() {
                    var n = 0
                    override fun read(): Int = if (n++ < 100) 7 else throw IOException("gone")
                    override fun read(b: ByteArray, off: Int, len: Int): Int = if (n < 100) { n += 1; b[off] = 7; 1 } else throw IOException("gone")
                } else ByteArrayInputStream(h.bytes[i])
            })
        assertTrue(out[0] is FileState.Offered)
        assertEquals(FileState.Failed(Why.Copy("SourceReadFailed")), out[1])
        assertTrue(out[2] is FileState.Offered)
        assertEquals(4, names(d).size) // two offered copies with markers; nothing of the failed one
    }

    @Test fun `a copy the offerer does not take is deleted at once, and the others are unaffected`() {
        val d = dir()
        val h = Harness(List(3) { Random.nextBytes(1000) })
        h.accept = { it != 1 }
        val out = batch(d, h.bytes).run(3, cap = 1_000_000, held = h::held, free = plenty, open = h::open, offerer = h.offerer(), cancelled = { false }, nowMs = { 0 })
        assertEquals(FileState.Failed(Why.NotOffered), out[1])
        assertEquals(listOf(0, 2), h.offered.map { it.first })
        val kept = h.offered.map { it.third }.flatMap { listOf("$it.bin", "$it.json") }.toSet()
        assertEquals(kept, names(d))
    }

    @Test fun `an offerer that throws counts as not taken - the copy is deleted, the batch goes on`() {
        val d = dir()
        val h = Harness(List(2) { Random.nextBytes(300) })
        var calls = 0
        val out = batch(d, h.bytes).run(3, cap = 1_000_000, held = h::held, free = plenty, open = h::open, cancelled = { false }, nowMs = { 0 },
            offerer = { _, _, _, _, _ -> calls++; if (calls == 1) error("session dropped") else true })
        assertEquals(FileState.Failed(Why.NotOffered), out[0])
        assertTrue(out[1] is FileState.Offered)
        assertEquals(2, names(d).size)
    }

    @Test fun `cancelling mid-batch copies nothing further and leaves nothing it still owned`() {
        val d = dir()
        val h = Harness(List(4) { Random.nextBytes(800) })
        var stop = false
        h.accept = { i -> if (i == 1) stop = true; true }
        val out = batch(d, h.bytes).run(3, cap = 1_000_000, held = h::held, free = plenty, open = h::open, offerer = h.offerer(), cancelled = { stop }, nowMs = { 0 })
        assertTrue(out[0] is FileState.Offered && out[1] is FileState.Offered)
        assertEquals(listOf(FileState.Cancelled, FileState.Cancelled), out.drop(2))
        assertEquals(listOf(0, 1), h.opens)
        assertEquals(4, names(d).size) // only the two offered copies and their markers
    }

    @Test fun `a cancel during a copy deletes that partial and every later file is cancelled unread`() {
        val d = dir()
        val big = Random.nextBytes(300_000)
        val h = Harness(listOf(big, big, big))
        var reads = 0
        val out = batch(d, h.bytes).run(3, cap = 1_000_000_000, held = h::held, free = plenty, offerer = h.offerer(), nowMs = { 0 },
            open = h::open, cancelled = { reads++ > 3 })
        assertEquals(FileState.Cancelled, out[0])
        assertEquals(listOf(FileState.Cancelled, FileState.Cancelled), out.drop(1))
        assertEquals(listOf(0), h.opens)
        assertEquals(emptySet<String>(), names(d))
    }

    @Test fun `space is judged per file over everything held - a later file that no longer fits fails alone`() {
        val d = dir()
        val h = Harness(listOf(Random.nextBytes(1000), Random.nextBytes(1000)))
        // The second file claims 3 GiB (a claim, not bytes written), so its margin is above the 256 MiB
        // floor and Σ changes it: free fits it alone, and 50 bytes short once the first 1,000 are held.
        val claim = 3 * gib
        val free = claim + ShareStaging.margin(claim) + 50
        assertTrue("control: alone it fits", ShareAdmission.forCopy(3, claim, 0, free, 10 * gib) is ShareAdmission.Copy.Go)
        val out = ShareBatch(d, ShareSelection.newGroupId(), listOf(1000L, claim))
            .run(3, cap = 10 * gib, held = h::held, free = { free }, open = h::open, offerer = h.offerer(), cancelled = { false }, nowMs = { 0 })
        assertTrue(out[0] is FileState.Offered)
        val why = (out[1] as FileState.Failed).why as Why.Admission
        assertTrue(why.verdict.toString(), why.verdict is ShareAdmission.Copy.NoSpace)
        assertEquals(listOf(0), h.opens)
    }

    @Test fun `discardUnoffered is idempotent and never touches another attempt's files`() {
        val d = dir()
        val theirs = ShareStaging.newAttemptId().also { File(d, "$it.bin").writeText("not the batch's") }
        val h = Harness(List(2) { Random.nextBytes(100) })
        val b = batch(d, h.bytes)
        b.run(3, cap = 1_000_000, held = h::held, free = plenty, open = h::open, offerer = h.offerer(), cancelled = { false }, nowMs = { 0 })
        assertEquals(0, b.discardUnoffered())
        assertEquals(0, b.discardUnoffered())
        assertTrue(File(d, "$theirs.bin").exists())
    }

    @Test fun `a batch is one to ten files`() {
        for (n in listOf(0, 11)) {
            try {
                ShareBatch(dir(), ShareSelection.newGroupId(), List(n) { 1L })
                throw AssertionError("n=$n was accepted")
            } catch (expected: IllegalArgumentException) {
            }
        }
        assertFalse(ShareSelection.MAX_FILES > ShareOffer.MAX_LIVE_OFFERS_V3)
    }

    @Test fun `the sheet closing while a file copies - that copy is deleted, not offered, and nothing after it is read`() {
        val d = dir()
        val h = Harness(List(3) { Random.nextBytes(700) })
        lateinit var b: ShareBatch
        b = batch(d, h.bytes)
        val out = b.run(3, cap = 1_000_000, held = h::held, free = plenty, offerer = h.offerer(), cancelled = { false }, nowMs = { 0 },
            open = { i -> if (i == 1) b.discardUnoffered(); h.open(i) })
        assertTrue(out[0] is FileState.Offered)
        assertEquals(listOf(FileState.Cancelled, FileState.Cancelled), out.drop(1))
        assertEquals(listOf(0), h.offered.map { it.first })
        assertEquals(listOf(0, 1), h.opens)
        assertEquals("only the first offer's copy and marker", 2, names(d).size)
    }

    @Test fun `a close from another thread waits for an offer in flight - the handed-over copy is never deleted under it`() {
        val d = dir()
        val h = Harness(listOf(Random.nextBytes(600)))
        val inOffer = java.util.concurrent.CountDownLatch(1)
        val release = java.util.concurrent.CountDownLatch(1)
        val b = batch(d, h.bytes)
        var removed = -1
        val closer = Thread {
            inOffer.await()
            removed = b.discardUnoffered()
        }
        closer.start()
        val out = b.run(3, cap = 1_000_000, held = h::held, free = plenty, open = h::open, cancelled = { false }, nowMs = { 0 },
            offerer = { _, _, _, _, _ -> inOffer.countDown(); release.await(200, java.util.concurrent.TimeUnit.MILLISECONDS); true })
        release.countDown()
        closer.join(2000)
        assertTrue(out[0] is FileState.Offered)
        assertEquals("the close found nothing of the batch's left to delete", 0, removed)
        assertEquals(2, names(d).size)
    }

    @Test fun `the sheet closing between two files - the next file is never opened`() {
        val d = dir()
        val h = Harness(List(3) { Random.nextBytes(400) })
        lateinit var b: ShareBatch
        b = batch(d, h.bytes)
        val out = b.run(3, cap = 1_000_000, held = h::held, free = plenty, open = h::open, cancelled = { false }, nowMs = { 0 },
            offerer = { _, _, _, _, _ -> b.discardUnoffered(); true })
        assertTrue(out[0] is FileState.Offered)
        assertEquals(listOf(FileState.Cancelled, FileState.Cancelled), out.drop(1))
        assertEquals("nothing after the close was read", listOf(0), h.opens)
    }
}
