package com.chetan.connectsuite.sync.v2

import com.chetan.connectsuite.core.protocol.ErrorCode
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.longOrNull
import kotlinx.serialization.json.put
import kotlinx.serialization.json.putJsonArray
import kotlinx.serialization.json.add
import java.security.MessageDigest

/**
 * The block rule for `fs.blocks` pulls (docs/protocol.md → Block-verified, resumable pulls). Pure, so
 * a JVM test reaches it; the Mac's `fsBlocks.ts` implements the same rule, and both are held to
 * `docs/fixtures/fs-blocks.json`, generated by a third, independent implementation.
 */
object FsBlocks {
    /** Pulls at or below this keep the pre-hash path; blocks apply only above it. */
    const val BLOCK_PULL_ABOVE_BYTES: Long = 64L * 1024 * 1024
    const val MIN_BLOCK_SIZE: Int = 1 shl 17 // 128 KiB
    const val MAX_BLOCK_SIZE: Int = 1 shl 24 // 16 MiB
    const val MAX_BLOCKS_TARGET: Long = 2000
    /** At most this many digests in one `fs.transfer.blocks` event. */
    const val MAX_DIGESTS_PER_EVENT: Int = 256

    /** The smallest power of two in [128 KiB, 16 MiB] giving ≤ 2000 blocks; 16 MiB when none does. */
    fun blockSizeFor(size: Long): Int {
        var bs = MIN_BLOCK_SIZE
        while (bs <= MAX_BLOCK_SIZE) {
            if (blockCountFor(size, bs) <= MAX_BLOCKS_TARGET) return bs
            bs = bs shl 1
        }
        return MAX_BLOCK_SIZE
    }

    fun blockCountFor(size: Long, blockSize: Int): Long = (size + blockSize - 1) / blockSize

    /** SHA-256 over the first [n] raw digests (all by default): `manifestRoot` / `prefixRoot(n)`. */
    fun rootOf(digests: List<ByteArray>, n: Int = digests.size): ByteArray {
        val md = MessageDigest.getInstance("SHA-256")
        for (i in 0 until n) md.update(digests[i])
        return md.digest()
    }

    fun hex(bytes: ByteArray): String = bytes.joinToString("") { "%02x".format(it) }

    /** An accepted resume: the first [verifiedBlocks] blocks are the Mac's, and must hash to [prefixRoot]. */
    data class Resume(val verifiedBlocks: Long, val prefixRoot: String) {
        fun from(blockSize: Int): Long = verifiedBlocks * blockSize
    }

    /** The phone's answer to a `resume` object in `fs.transfer.begin`. */
    sealed interface ResumeAnswer {
        data class Accepted(val resume: Resume) : ResumeAnswer
        /** `why` is the contract's: `source-changed` or `bad-request`. */
        data class Refused(val why: String, val detail: String) : ResumeAnswer
    }

    private val HEX64 = Regex("^[0-9a-f]{64}$")

    /**
     * Decides a resume request against the source as it is **now**. Provisional: the prefix itself is
     * re-hashed by [BlockPullSender] before the first new byte (owner decision D1). Any field missing or
     * of the wrong type is `bad-request`, never a guess.
     */
    fun decideResume(
        reqSize: Long?, reqMtimeMs: Long?, reqBlockSize: Long?, reqVerifiedBlocks: Long?, reqPrefixRoot: String?,
        size: Long, mtimeMs: Long,
    ): ResumeAnswer {
        if (reqSize == null || reqMtimeMs == null || reqBlockSize == null || reqVerifiedBlocks == null || reqPrefixRoot == null) {
            return ResumeAnswer.Refused("bad-request", "a resume needs size, mtimeMs, blockSize, verifiedBlocks and prefixRoot")
        }
        if (reqSize != size || reqMtimeMs != mtimeMs) {
            return ResumeAnswer.Refused("source-changed", "the Mac holds $reqSize bytes @ $reqMtimeMs; the file is now $size @ $mtimeMs")
        }
        val bs = blockSizeFor(size)
        if (reqBlockSize != bs.toLong()) return ResumeAnswer.Refused("bad-request", "blockSize $reqBlockSize where the rule gives $bs")
        val count = blockCountFor(size, bs)
        if (reqVerifiedBlocks < 1 || reqVerifiedBlocks >= count) {
            return ResumeAnswer.Refused("bad-request", "verifiedBlocks $reqVerifiedBlocks outside 1..${count - 1}")
        }
        if (!HEX64.matches(reqPrefixRoot)) return ResumeAnswer.Refused("bad-request", "prefixRoot is not 64 lowercase hex characters")
        return ResumeAnswer.Accepted(Resume(reqVerifiedBlocks, reqPrefixRoot))
    }

    /**
     * Reads the `resume` object of an `fs.transfer.begin` request. Null when there is none; a present
     * value that is not an object, or fields of the wrong JSON type, reach [decideResume] as null and
     * are refused `bad-request` there — never coerced (`"512"` is not 512).
     */
    fun parseResume(raw: JsonElement?, size: Long, mtimeMs: Long): ResumeAnswer? {
        if (raw == null || raw is kotlinx.serialization.json.JsonNull) return null
        val o = raw as? JsonObject ?: return ResumeAnswer.Refused("bad-request", "resume is not an object")
        fun long(k: String): Long? = (o[k] as? JsonPrimitive)?.takeIf { !it.isString }?.longOrNull
        val root = (o["prefixRoot"] as? JsonPrimitive)?.takeIf { it.isString }?.content
        return decideResume(long("size"), long("mtimeMs"), long("blockSize"), long("verifiedBlocks"), root, size, mtimeMs)
    }

    /** The ack's `resume` field: `{accepted:true, from}` or `{accepted:false, why}`; null when none was asked. */
    fun resumeAck(answer: ResumeAnswer?, blockSize: Int): JsonObject? = when (answer) {
        null -> null
        is ResumeAnswer.Accepted -> buildJsonObject { put("accepted", true); put("from", answer.resume.from(blockSize)) }
        is ResumeAnswer.Refused -> buildJsonObject { put("accepted", false); put("why", answer.why) }
    }

    /**
     * Whether a pull takes the block path: `fs.blocks` negotiated on this session **and** the file above
     * the 64 MiB pre-hash ceiling. Everything else — an older Mac, a release build, a small file — keeps
     * the old path exactly.
     */
    fun appliesTo(negotiated: Map<String, Int>, size: Long): Boolean =
        (negotiated[com.chetan.connectsuite.core.link.Extensions.FS_BLOCKS] ?: 0) >= 1 && size > BLOCK_PULL_ABOVE_BYTES

    /** The offset a bulk claim must carry for this pull: the accepted resume's start, else 0. */
    fun requiredOffset(resume: Resume?, blockSize: Int): Long = resume?.from(blockSize) ?: 0L

    /** One `fs.transfer.blocks` payload. */
    fun blocksPayload(transferId: String, first: Long, digests: List<String>): JsonObject = buildJsonObject {
        put("transferId", transferId)
        put("first", first)
        putJsonArray("sha256") { digests.forEach { add(it) } }
    }

    /**
     * `fs.transfer.done` for a block pull, from how [BlockPullSender] ended. `bytes` is the file's
     * position reached — the whole size on success, whatever a resume started from included.
     */
    fun donePayload(
        transferId: String, name: String, outcome: BlockPullSender.Outcome, size: Long, blockSize: Int,
        resume: Resume?, elapsedMs: Long,
    ): JsonObject {
        val reached = requiredOffset(resume, blockSize) + outcome.bytesSent
        return buildJsonObject {
            put("transferId", transferId)
            put("elapsedMs", elapsedMs)
            when (outcome) {
                is BlockPullSender.Outcome.Sent -> {
                    put("ok", true)
                    put("bytes", reached)
                    // The sender's word: every block was read and hashed and the source held still. The
                    // Mac decides whether what it wrote matches.
                    put("verified", true)
                    put("sha256", outcome.sha256)
                    put("blockSize", blockSize)
                    put("blockCount", outcome.blockCount)
                    put("manifestRoot", outcome.manifestRoot)
                }
                is BlockPullSender.Outcome.SourceChanged -> {
                    put("ok", false)
                    put("code", ErrorCode.SOURCE_CHANGED)
                    put("why", outcome.why)
                    put("message", if (outcome.why == "prefix-mismatch") {
                        "$name changed on the phone since the transfer paused, so it has to start again."
                    } else {
                        "$name changed on the phone while it was being sent, so it was not saved."
                    })
                    put("bytes", reached)
                    put("verified", false)
                }
                is BlockPullSender.Outcome.Cancelled -> {
                    put("ok", false)
                    put("code", ErrorCode.TRANSFER_FAILED)
                    put("message", "$name stopped after $reached bytes.")
                    put("bytes", reached)
                    put("verified", false)
                }
            }
        }
    }

    /**
     * Hashes a stream into fixed-size blocks whatever the read boundaries, and hands each closed block's
     * digest to [onBlock] in order. [finish] closes the short last block.
     */
    class Hasher(val blockSize: Int, private val onBlock: (index: Long, digest: ByteArray) -> Unit = { _, _ -> }) {
        val digests = mutableListOf<ByteArray>()
        private var current: MessageDigest = MessageDigest.getInstance("SHA-256")
        private var filled = 0
        /** Index of the next block to close; starts at [startIndex] for a resumed stream. */
        var nextIndex: Long = 0
            private set

        constructor(blockSize: Int, startIndex: Long, onBlock: (Long, ByteArray) -> Unit) : this(blockSize, onBlock) {
            nextIndex = startIndex
        }

        fun update(buffer: ByteArray, offset: Int = 0, length: Int = buffer.size) {
            var at = offset
            val end = offset + length
            while (at < end) {
                val take = minOf(blockSize - filled, end - at)
                current.update(buffer, at, take)
                filled += take
                at += take
                if (filled == blockSize) close()
            }
        }

        fun finish(): List<ByteArray> {
            if (filled > 0) close()
            return digests
        }

        private fun close() {
            val d = current.digest()
            digests.add(d)
            onBlock(nextIndex, d)
            nextIndex += 1
            current = MessageDigest.getInstance("SHA-256")
            filled = 0
        }
    }
}
