package com.chetan.connectsuite.sync.v2

import java.io.File
import java.io.InputStream
import java.security.SecureRandom
import java.util.Base64

/**
 * **Stage B groundwork — Gallery / My Files multi-select. PROPOSED, not wired, not registered.**
 * docs/feature-a-multi-offer-proposal.md rev 3 §3; docs/protocol.md → Share → Version 3 (the optional
 * `group`). Nothing here is reachable: the manifest registers no `SEND_MULTIPLE` (`ShareManifestTest`
 * holds that), no activity calls these functions, and the only cap on copies held at once is
 * [ShareAdmission.APPROVED_CAP], which is `null` — so [ShareBatch.admitSelection] refuses every
 * selection of more than one file. Pure JVM, so a test reaches every rule with generated bytes.
 *
 * ### The rules, each in one place
 *
 * - **A selection is taken or refused as a whole, before anything is read** ([ShareSelection.decide]).
 *   Over [MAX_FILES] is refused with the limit stated — **never silently truncated**. One unreadable
 *   item (not `content:`, a folder) refuses the selection and names its position.
 * - **Files are copied one at a time, in selection order**, each through the same admission the
 *   one-file sheet uses ([ShareAdmission.forCopy]) with everything already held counted, and the same
 *   copy ([ShareStaging.copy]).
 * - **Every file is its own offer.** A copy that succeeds is handed to [ShareBatch.Offerer]; from then
 *   its end belongs to `ShareFeature`, never to the batch. A copy the offerer does not take is deleted
 *   at once. `group` is display only and authorises nothing.
 * - **Per-file cleanup, and nothing left behind.** A failed or cancelled file leaves no bytes; a cancel
 *   deletes every copy not yet handed over and copies nothing further; [ShareBatch.discardUnoffered] is
 *   idempotent. A file that fails does not stop the others — its failure is stated.
 */
object ShareSelection {

    const val ACTION_SEND_MULTIPLE = "android.intent.action.SEND_MULTIPLE"

    /** Files per selection — the proposal's figure, equal to the live-offer limit. **Proposed, not approved.** */
    const val MAX_FILES = ShareOffer.MAX_LIVE_OFFERS_V3

    /** One shared item as the activity would read it: its URI's scheme and its resolved MIME type. */
    data class Item(val scheme: String?, val mime: String)

    sealed interface Decision {
        data class Take(val count: Int) : Decision
        data class Refuse(val reason: Refusal, val index: Int? = null) : Decision
    }

    enum class Refusal { NOT_A_SEND_MULTIPLE, NO_FILES, TOO_MANY, NOT_CONTENT, FOLDER, ANOTHER_IN_PROGRESS }

    /**
     * Whether a `SEND_MULTIPLE` can be taken. [items] are every stream, from `EXTRA_STREAM` or
     * `ClipData`, in the order the sender gave them — which is the order they would be copied and
     * offered. [index] on a refusal is 1-based, so the sheet can say *"the 3rd item"*.
     */
    fun decide(action: String?, items: List<Item>, otherAttemptLive: Boolean): Decision {
        if (action != ACTION_SEND_MULTIPLE) return Decision.Refuse(Refusal.NOT_A_SEND_MULTIPLE)
        if (items.isEmpty()) return Decision.Refuse(Refusal.NO_FILES)
        if (items.size > MAX_FILES) return Decision.Refuse(Refusal.TOO_MANY)
        items.forEachIndexed { i, item ->
            val scheme = item.scheme ?: return Decision.Refuse(Refusal.NOT_CONTENT, i + 1)
            if (!scheme.equals("content", ignoreCase = true)) return Decision.Refuse(Refusal.NOT_CONTENT, i + 1)
            if (ShareNames.isDirectory(item.mime)) return Decision.Refuse(Refusal.FOLDER, i + 1)
        }
        if (otherAttemptLive) return Decision.Refuse(Refusal.ANOTHER_IN_PROGRESS)
        return Decision.Take(items.size)
    }

    /** `group` on a Stage B offer — display only. `index` is 1…count, count 1…[MAX_FILES]. */
    data class Group(val id: String, val index: Int, val count: Int) {
        init {
            require(GROUP_ID.matches(id)) { "a group id is g- and 22 base64url characters" }
            require(count in 1..MAX_FILES) { "count is 1…$MAX_FILES, got $count" }
            require(index in 1..count) { "index is 1…$count, got $index" }
        }
    }

    private val GROUP_ID = Regex("^g-[A-Za-z0-9_-]{22}$")
    private val random = SecureRandom()

    fun newGroupId(): String {
        val bytes = ByteArray(16).also { random.nextBytes(it) }
        return "g-" + Base64.getUrlEncoder().withoutPadding().encodeToString(bytes)
    }
}

/** One selection's private copies, made one at a time — see [ShareSelection]. */
class ShareBatch(
    private val dir: File,
    private val groupId: String,
    /** The provider's claimed size of each item, in selection order (`null` when it gave none). */
    private val expected: List<Long?>,
) {
    init {
        require(expected.size in 1..ShareSelection.MAX_FILES) { "a batch holds 1…${ShareSelection.MAX_FILES} files" }
    }

    sealed interface FileState {
        data object Pending : FileState
        data object Copying : FileState
        /** Handed to the offerer: its end is `ShareFeature`'s now. */
        data class Offered(val offerId: String, val bytes: Long, val sha256: String) : FileState
        data class Failed(val why: Why) : FileState
        data object Cancelled : FileState
    }

    /** Why one file was not offered. Each is that file's alone; the others carry on. */
    sealed interface Why {
        data class Admission(val verdict: ShareAdmission.Copy) : Why
        data class Copy(val outcome: String) : Why
        data object OpenFailed : Why
        /** Copied, but the offerer did not take it (no session, busy, not negotiated): the copy was deleted. */
        data object NotOffered : Why
    }

    /** Whether a whole selection may start: count, and the approved cap over every known size. */
    sealed interface Admission {
        data object Go : Admission
        /** More than one file and no cap on copies held at once is approved: multi-select stays off. */
        data object CapNotApproved : Admission
        /** Known sizes plus what is already held pass the approved cap. [known] excludes unknown sizes. */
        data class OverCap(val heldBefore: Long, val known: Long, val cap: Long) : Admission
    }

    fun interface Offerer {
        /** Offer the staged copy [attemptId]; true only if an offer was made and took ownership of it. */
        fun offer(index: Int, group: ShareSelection.Group, attemptId: String, bytes: Long, sha256: String): Boolean
    }

    private val states = MutableList<FileState>(expected.size) { FileState.Pending }
    /** Copies this batch still owns (staged, not handed over). Deleted by any end that is not an offer. */
    private val owned = LinkedHashSet<String>()
    /**
     * Guards the hand-off, as `ShareToMacModel`'s lock does for one file: a copy is offered, or deleted
     * by [discardUnoffered], never both and never half. [closed] is set by [discardUnoffered] (the sheet
     * going away): from then on nothing is copied or offered.
     */
    private val lock = Any()
    @Volatile private var closed = false

    fun states(): List<FileState> = states.toList()

    companion object {
        /**
         * Before any copy: the selection as a whole. One file is the one-file rule and is never refused
         * here. **With [cap] null — as shipped — any selection of more than one file is refused.**
         */
        fun admitSelection(expected: List<Long?>, heldBefore: Long, cap: Long?): Admission {
            if (expected.size <= 1) return Admission.Go
            if (cap == null) return Admission.CapNotApproved
            val known = expected.filterNotNull().sum()
            return if (heldBefore + known > cap) Admission.OverCap(heldBefore, known, cap) else Admission.Go
        }
    }

    /**
     * Copy every file in order. [held] is `Σ` outside this batch **plus** every copy this batch has
     * handed over (they are the offerer's now, and still on disk); the batch adds the copy it is about
     * to judge on its own. [open] reads item `i` (0-based) while the grant is held; [free] is re-read
     * for each file. Returns the final states. Never throws for a single file's failure.
     */
    fun run(
        version: Int,
        cap: Long?,
        held: () -> Long,
        free: () -> Long,
        open: (Int) -> InputStream,
        offerer: Offerer,
        cancelled: () -> Boolean,
        nowMs: () -> Long,
    ): List<FileState> {
        for (i in expected.indices) {
            if (cancelled() || closed) {
                cancelFrom(i)
                break
            }
            states[i] = FileState.Copying
            val verdict = ShareAdmission.forCopy(version, expected[i], held(), free(), cap)
            if (verdict !is ShareAdmission.Copy.Go) {
                states[i] = FileState.Failed(Why.Admission(verdict))
                continue
            }
            val input = runCatching { open(i) }.getOrElse {
                states[i] = FileState.Failed(Why.OpenFailed)
                continue
            }
            val id = ShareStaging.newAttemptId()
            synchronized(lock) { owned += id }
            val outcome = ShareStaging.copy(
                source = input, dir = dir, attemptId = id, limit = verdict.limit,
                available = free, cancelled = cancelled, nowMs = nowMs(),
            )
            if (outcome !is ShareStaging.Outcome.Staged) {
                // ShareStaging.copy deletes its own partial on every non-success; nothing of it stays.
                synchronized(lock) { owned -= id }
                states[i] = if (outcome is ShareStaging.Outcome.Cancelled) FileState.Cancelled else FileState.Failed(Why.Copy(outcome::class.simpleName ?: "?"))
                if (outcome is ShareStaging.Outcome.Cancelled) {
                    cancelFrom(i + 1)
                    break
                }
                continue
            }
            val group = ShareSelection.Group(groupId, i + 1, expected.size)
            val stop = synchronized(lock) {
                if (closed) {
                    // The sheet went away while this file was copying: it is not offered, and not kept.
                    ShareStaging.discard(dir, id)
                    owned -= id
                    states[i] = FileState.Cancelled
                    return@synchronized true
                }
                val taken = runCatching { offerer.offer(i, group, id, outcome.bytes, outcome.sha256) }.getOrDefault(false)
                owned -= id
                if (taken) {
                    states[i] = FileState.Offered(id, outcome.bytes, outcome.sha256)
                } else {
                    ShareStaging.discard(dir, id)
                    states[i] = FileState.Failed(Why.NotOffered)
                }
                false
            }
            if (stop) {
                cancelFrom(i + 1)
                break
            }
        }
        return states()
    }

    /**
     * The sheet is going away: nothing further is copied or offered, and every copy this batch still
     * owns is deleted. Waits for an offer in flight to finish, so a copy is never deleted mid-hand-off.
     * Idempotent; a handed-over copy is never touched. A copy still being written is left to [run],
     * which deletes it when its copy returns and sees [closed].
     */
    fun discardUnoffered(): Int = synchronized(lock) {
        closed = true
        var removed = 0
        for (id in owned.toList()) {
            removed += ShareStaging.discard(dir, id)
            owned -= id
        }
        removed
    }

    private fun cancelFrom(from: Int) {
        for (j in from until states.size) if (states[j] == FileState.Pending || states[j] == FileState.Copying) states[j] = FileState.Cancelled
    }
}
