#!/usr/bin/env python3
"""Generates docs/fixtures/pairing-v2-vectors.json — the pairing v2 proofs (docs/protocol.md → Pairing
(version 2)) computed by an implementation that is neither the Mac's nor the phone's: Python's standard
`hmac` and `hashlib`. Both apps' tests read the JSON and must reproduce every byte. Deterministic inputs,
no randomness, so re-running it reproduces the file exactly.

    python3 -I docs/fixtures/pairing-v2-vectors.py > docs/fixtures/pairing-v2-vectors.json
"""
import hashlib
import hmac
import json

LABEL = b"sidekick/pair/v2"


def colon(b: bytes) -> str:
    return ":".join(f"{x:02X}" for x in b)


def transcript(role: str, fm: bytes, fp: bytes, nm: bytes, np: bytes) -> bytes:
    return LABEL + b"\x00" + role.encode("ascii") + b"\x00" + fm + fp + nm + np


def pattern(seed: int) -> bytes:
    return hashlib.sha256(f"pairing-v2-vector-{seed}".encode()).digest()


vectors = []
for i in range(3):
    k, fm, fp, nm, np = (pattern(10 * i + j) for j in range(5))
    entry = {
        "name": f"vector-{i}",
        "secret": k.hex(),
        "macFingerprint": colon(fm),
        "phoneFingerprint": colon(fp),
        "macNonce": nm.hex(),
        "phoneNonce": np.hex(),
    }
    for role in ("phone", "mac"):
        t = transcript(role, fm, fp, nm, np)
        entry[f"{role}Transcript"] = t.hex()
        entry[f"{role}Proof"] = hmac.new(k, t, hashlib.sha256).hexdigest()
    vectors.append(entry)

print(json.dumps({
    "about": "Pairing v2 proofs from an independent implementation (Python hmac/hashlib). "
             "Generated by pairing-v2-vectors.py; do not edit by hand.",
    "label": LABEL.decode(),
    "vectors": vectors,
}, indent=2))
